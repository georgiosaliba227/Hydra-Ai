"""Public, fixed recipe selection; no records, physiological labels or transport."""
import json

from ai.forecasting.muse_synthetic import PLAN_VERSION as VERSION, RECIPES, validate_plan
from .meta_provider import ProviderReply, strict_json
from .recognition import RecognitionUnavailable

MODEL = "muse-wonder-1.0"
OUTPUT_LIMIT = 512
CATALOG = {
    "base": "Training-only bootstrap of existing simulated anchor rates; bounded +/-40 mL observation noise.",
    "missing_covariates": "The same label mechanism; independently mask initial mass and age with probability 0.5.",
    "wide_noise": "Bounded +/-150 mL observation noise, solely a software stress assumption.",
    "outlier": "Base noise plus +500 mL measurement contamination on every fourth augmented row, solely a stress setting.",
}


def fixed_payload() -> dict:
    schema = {"type": "object", "additionalProperties": False, "required": ["version", "training_weights"],
        "properties": {"version": {"type": "string", "enum": [VERSION]}, "training_weights": {
            "type": "object", "additionalProperties": False, "required": list(RECIPES),
            "properties": {key: {"type": "integer", "enum": [1, 2]} for key in RECIPES}}}}
    context = {"task": "Choose one or two training-sized augmentation blocks for each recipe.",
        "recipes": CATALOG, "constraints": [
            "These are invented software scenarios, not measured physiology or a person's calibration history.",
            "A frozen base cohort and grouped holdouts are prepared independently; only TRAIN is augmented.",
            "The generator's source anchors are restricted to one study's existing training split and never sent here.",
            "Numeric labels are generated by Hydra with documented mass-balance assumptions, not by you.",
            "Weather, intensity, HR, HRV, caffeine and creatine have no numerical effect.",
            "All held-out robustness checks are mandatory regardless of your weights.",
            "Return only the schema. No prose, measurements, effects, prescriptions, tools or new fields."]}
    return {"model": MODEL, "store": False, "stream": False, "background": False,
        "max_output_tokens": OUTPUT_LIMIT, "reasoning": {"effort": "minimal"},
        "text": {"format": {"type": "json_schema", "name": "muse_synthetic_training_plan", "strict": True, "schema": schema}},
        "input": [{"role": "user", "content": [{"type": "input_text",
            "text": json.dumps(context, sort_keys=True, separators=(",", ":"), allow_nan=False)}]}]}


def validate_payload(payload: dict) -> None:
    try:
        exact = json.dumps(payload, sort_keys=True, separators=(",", ":"), allow_nan=False)
    except (TypeError, ValueError):
        raise ValueError("Only the fixed public simulation-plan payload is supported") from None
    if exact != json.dumps(fixed_payload(), sort_keys=True, separators=(",", ":"), allow_nan=False):
        raise ValueError("Only the fixed public simulation-plan payload is supported")


def parse_reply(reply: ProviderReply) -> dict:
    try:
        body = reply.body
        if (reply.status != 200 or body.get("model") != MODEL or body.get("status") != "completed"
                or body.get("error") is not None or body.get("incomplete_details") is not None
                or not isinstance(body["output"], list)):
            raise ValueError
        messages = []
        for item in body["output"]:
            if not isinstance(item, dict):
                raise ValueError
            if item.get("type") != "reasoning":
                messages.append(item)
        if len(messages) != 1:
            raise ValueError
        message = messages[0]
        if (message.get("type") != "message" or message.get("role") != "assistant"
                or message.get("status") != "completed" or len(message["content"]) != 1):
            raise ValueError
        part = message["content"][0]
        if part.get("type") != "output_text" or not isinstance(part.get("text"), str) or len(part["text"].encode()) > 8192:
            raise ValueError
        return validate_plan(strict_json(part["text"]))
    except (KeyError, TypeError, ValueError, AttributeError, IndexError):
        raise RecognitionUnavailable() from None
