VERSION = "hydration-analysis-v1"
LIMITATIONS = [
    "Research-only exercise loss proxy; not clinically validated or a measure of total body hydration.",
    "Logged intake is an incomplete record; no log does not establish no consumption.",
    "Beverage volume, composition water and physiological retention are different quantities.",
    "A planned forecast is never counted as an already incurred loss.",
    "Exercise accounting omits urine and other losses and is not a full fluid balance or drinking target.",
    "Environmental values describe supplied conditions; no unvalidated weather adjustment is applied.",
    "Heart rate, HRV, caffeine and creatine do not trigger hydration diagnoses or automatic adjustments.",
    "Local sections are deterministic; only a separately labeled saved explanation was generated by Muse Wonder.",
    "Calibration history is retained by the caller; this endpoint does not persist the request or send it to Meta.",
]


def _sum(values: Iterable[float]) -> float:
    return representable(sum((exact(value) for value in values), Fraction()), "intake_total")


def _composition(logs: tuple[BeverageLog, ...]) -> dict:
    contributions = tuple(calculate_contribution(log) for log in logs)
    result = {"sodium_mg": None, "potassium_mg": None, "status": "unknown", "provenance": []}
    any_known = False
    for field in ("sodium_mg", "potassium_mg"):
        known = [getattr(value, field) for value in contributions if getattr(value, field) is not None]
        complete = bool(logs) and len(known) == len(logs)
        result[field] = _sum(known) if complete else None
        result[field.replace("_mg", "_status")] = "complete" if complete else "partial" if known else "unknown"
        any_known |= bool(known)
    if any_known:
        result["status"] = "complete" if all(result[field] is not None for field in ("sodium_mg", "potassium_mg")) else "partial"
        result["provenance"] = list(dict.fromkeys(source for log in logs if log.nutrition is not None
            and (log.nutrition.sodium_mg is not None or log.nutrition.potassium_mg is not None)
            for source in log.nutrition.provenance))
    return result


def _intake(logs: tuple[BeverageLog, ...], generated_at: datetime, timezone_name: str, *, synthetic: bool) -> dict:
    local_zone = zone(timezone_name)
    local_date = generated_at.astimezone(local_zone).date()
    start = datetime.combine(local_date, time.min, tzinfo=local_zone).astimezone(timezone.utc)
    selected = tuple(log for log in logs if start <= log.consumed_at.astimezone(timezone.utc) <= generated_at)
    summary = summarize_day(selected, local_date, timezone_name)
    return {"status": "unavailable_in_synthetic" if synthetic else "logged", "local_date": local_date,
            "start_utc": utc_string(start), "end_utc": utc_string(generated_at), "timezone": timezone_name,
            "beverage_count": None if synthetic else len(selected),
            "beverage_volume_ml": None if synthetic else summary.beverage_total_ml,
            "water_ml": None if synthetic or not selected else summary.estimated_water_ml,
            "composition": _composition(selected), "completeness": "unverified",
            "provenance": [] if synthetic else list(summary.provenance)}


def _trends(logs: tuple[BeverageLog, ...], generated_at: datetime, timezone_name: str, *, synthetic: bool) -> dict:
    local_zone = zone(timezone_name)
    today = generated_at.astimezone(local_zone).date()
    start = today-timedelta(days=14)
    prior = tuple(log for log in logs if start <= log.consumed_at.astimezone(local_zone).date() < today
                  and log.consumed_at.astimezone(timezone.utc) <= generated_at)
    dates = sorted({log.consumed_at.astimezone(local_zone).date() for log in prior})
    totals = [summarize_day(prior, day, timezone_name).beverage_total_ml for day in dates]
    return {"window_days": 14, "logged_days": None if synthetic else len(dates),
            "beverage_lower_ml": min(totals) if totals else None,
            "beverage_upper_ml": max(totals) if totals else None,
            "kind": "descriptive_logged_intake_not_needs", "completeness": "unverified"}


def _wonder(exercise: Exercise | None, samples: tuple[SweatSample, ...], timezone_name: str,
            generated_at: datetime, *, synthetic: bool) -> dict:
    result = {"status": "not_applicable", "preview": None, "saved": None,
              "reason": None, "provider_called": False}
    if synthetic or exercise is None or exercise.actual is not None:
        result["reason"] = "personal_planned_workout_required"
    elif convert_time(exercise.starts_at, timezone.utc, "starts_at") < generated_at:
        result["reason"] = "planned_workout_started"
    else:
        try:
            result.update(status="preview_only", preview=preview(build_facts(exercise, samples, timezone_name, generated_at)))
        except (CalculationError, ValueError):
            # A local numerical result remains useful if this distinct explanation
            # schema cannot represent it. Never repair, dispatch or substitute facts.
            result.update(status="unavailable", reason="preview_unavailable")
    return result


def build_analysis(payload: WorkoutForecastInput, logs: tuple[BeverageLog, ...], *, generated_at: datetime,
                   personal_predictor: Callable[..., dict] | None = None, version: str = VERSION,
                   embedded_workout_wonder: bool = True) -> dict:
    synthetic = payload.mode == "synthetic_demo"
    exercise = payload.exercise.engine() if payload.exercise else None
    samples = tuple(sample.engine() for sample in payload.samples)
    numerical = (predict_workout(None, generated_at=generated_at, mode="synthetic_demo") if synthetic
                 else (personal_predictor or predict_longitudinal)(exercise, samples, generated_at=generated_at))
    # Defense in depth: callers cannot cause real log content to enter a demo.
    logs = () if synthetic else logs
    intake = _intake(logs, generated_at, payload.timezone, synthetic=synthetic)
    accounting = logged_intake_minus_measured_exercise_loss(logs, exercise, generated_at=generated_at, timezone=payload.timezone)
    factors = numerical.get("input_factors", {})
    environment = {"temperature_c": factors.get("temperature_c"), "humidity_percent": factors.get("humidity_percent"),
                   "intensity": factors.get("intensity"), "context_only": True,
                   "source": "server_synthetic" if synthetic else "user_reported" if exercise else "unavailable"}
    history = numerical.get("longitudinal_history", {})
    calibration = {"total_samples": history.get("total_samples", 0),
                   "comparable_samples": history.get("comparable_samples", 0),
                   "recent_samples": history.get("recent_samples", 0),
                   "personalization_status": numerical["personalization_status"], "history_retained_by_caller": True}
    missing = list(numerical.get("missing_inputs", []))
    if not synthetic:
        missing.append("intake_completeness")
        if intake["water_ml"] is None:
            missing.append("documented_water_composition")
        if intake["composition"]["status"] != "complete":
            missing.append("complete_electrolyte_composition")
    if environment["temperature_c"] is None or environment["humidity_percent"] is None:
        missing.append("environmental_context")
    trends = _trends(logs, generated_at, payload.timezone, synthetic=synthetic)
    wonder = (_wonder(exercise, samples, payload.timezone, generated_at, synthetic=synthetic) if embedded_workout_wonder
              else {"status": "not_applicable", "preview": None, "saved": None,
                    "reason": "comprehensive_v3_preview_required", "provider_called": False})

    def section(identifier: str, title: str, facts: dict, text: str, evidence_status: str = "context_only") -> dict:
        return {"id": identifier, "title": title, "facts": facts, "text": text,
                "evidence_status": "synthetic" if synthetic else evidence_status}

    estimated = numerical["status"] == "estimated"
    sections = [
        section("summary", "Hydration-related summary", {
            "forecast_status": numerical["status"], "logged_beverage_volume_ml": intake["beverage_volume_ml"],
            "intake_completeness": intake["completeness"], "research_only": True},
            "The available record combines logged beverage volume with a separate research exercise-loss estimate. "
            "It does not establish total body hydration or a required intake amount.", "estimated" if estimated else "insufficient_data"),
        section("workout_loss", "Workout fluid-loss estimate", {
            key: numerical[key] for key in ("status", "model_version", "value_ml", "lower_ml", "upper_ml", "units", "interval_kind", "sample_count")},
            "The numerical engine supplies this conditional mass-balance loss proxy and its uncertainty envelope. "
            "A planned estimate is separate from an observed loss." if estimated else
            "The numerical engine abstained. Missing or incompatible observations cannot be filled in by explanation text.",
            "estimated" if estimated else "insufficient_data"),
        section("activity", "Activity context", {
            "activity": factors.get("activity"), "duration_minutes": factors.get("duration_minutes"),
            "intensity": factors.get("intensity"),
            "prior_activity_sessions": sum(sample.conditions.activity == exercise.conditions.activity for sample in samples) if exercise else 0,
            "completed_measurement_present": exercise is not None and exercise.actual is not None},
            "Duration and activity describe the supplied workout. Prior sessions support a projection only when their "
            "conditions, protocol and measurement errors meet the numerical engine's comparability checks."),
        section("environment", "Environmental context", environment,
            "Supplied temperature and humidity are context. Different or missing conditions can prevent matching; "
            "these values do not create an additional numerical loss adjustment."),
        section("beverages", "Beverage and electrolyte context", intake,
            "Logged beverage volume is separate from documented water content and retention. Electrolyte totals "
            "are shown only when every included entry has that documented nutrient; unknown values remain absent."),
        section("trends", "Personal trends", trends | {
            "comparable_measured_sessions": calibration["comparable_samples"],
            "recent_comparable_sessions": calibration["recent_samples"]},
            "Historical logged-day totals describe records, not physiological needs. Days without logs are not "
            "measured zero-intake days. Comparable measurements, rather than intake alone, support calibration."),
        section("uncertainty", "Prediction uncertainty", {
            "data_sufficiency": numerical["data_sufficiency"], "interval_kind": numerical["interval_kind"],
            "missing_inputs": list(dict.fromkeys(missing)), "accounting_status": accounting["status"],
            "accounting_reasons": accounting["reasons"]},
            "Measurement error, incomplete logging and incompatible conditions limit interpretation. More history "
            "does not guarantee a narrower range. A historical envelope is not a validated future coverage guarantee."),
        section("measurement", "Measurement insights", {
            "suggestions": ["comparable_dry_pre_post_workout_mass", "same_window_consumed_fluid_and_urine_including_measured_zeros",
                            "independently_supported_instrument_error_bounds", "record_activity_intensity_and_environment"],
            "history_retained_by_caller": True},
            "A comparable completed workout with dry before-and-after weighing, recorded consumption and urine, "
            "timing and instrument error bounds can improve the evidence available for later predictions. "
            "Check mismatched windows and protocols before comparing measurements."),
    ]
    return {"version": version, "generated_at": utc_string(generated_at), "timezone": payload.timezone,
            "mode": payload.mode, "research_only": True, "text_origin": "deterministic_local",
            "numerical_forecast": numerical, "intake": intake, "exercise_accounting": accounting,
            "environmental_context": environment, "calibration": calibration, "missing_inputs": list(dict.fromkeys(missing)),
            "sections": sections, "wonder": wonder, "limitations": list(LIMITATIONS)}


def install_hydration_analysis_routes(app: FastAPI, to_engine: Callable[[dict], BeverageLog], *, error_response,
                                     path: str = "/v1/hydration-analysis", personal_predictor: Callable[..., dict] | None = None,
                                     version: str = VERSION, embedded_workout_wonder: bool = True) -> None:
    @app.post(path)
    def hydration_analysis(payload: WorkoutForecastInput, request: Request):
        generated_at = datetime.now(timezone.utc)
        # Synthetic demonstrations do not even read the user's beverage repository.
        logs = (() if payload.mode == "synthetic_demo" else
                tuple(to_engine(record) for record in request.app.state.repository.list_all("local-demo")))
        try:
            result = build_analysis(payload, logs, generated_at=generated_at, personal_predictor=personal_predictor,
                                    version=version, embedded_workout_wonder=embedded_workout_wonder)
        except CalculationError:
            raise HTTPException(422, "invalid_request") from None
        except Exception:
            # Model failure cannot expose private input/exception text or dispatch a fallback.
            return error_response("internal_error", 503, request.state.request_id)
        view = result["wonder"]["preview"]
        results_dir = request.app.state.wonder_results_dir
        if view and view["payload_sha256"] and results_dir:
            try:
                result["wonder"]["saved"] = load_workout(results_dir, view["payload_sha256"])
            except (OSError, ValueError):
                result["wonder"]["reason"] = "saved_result_unavailable"
        return jsonable_encoder(result)
